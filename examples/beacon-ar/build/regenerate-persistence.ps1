function Assert-ExactGeneratedDirectory {
    param(
        [Parameter(Mandatory = $true)]
        [string] $Directory,

        [Parameter(Mandatory = $true)]
        [string[]] $ExpectedFiles,

        [Parameter(Mandatory = $false)]
        [switch] $RequireCompiledMetadata
    )

    if (-not (Test-Path -LiteralPath $Directory -PathType Container)) {
        throw "Expected generated directory is missing: $Directory"
    }

    $actualEntries = @(Get-ChildItem -LiteralPath $Directory -Force)
    $unexpectedDirectories = @($actualEntries | Where-Object { $_.PSIsContainer })
    if ($unexpectedDirectories.Count -ne 0) {
        throw "Unexpected generated subdirectories: $($unexpectedDirectories.Name -join ', ')"
    }

    $actualFiles = @($actualEntries | Where-Object { -not $_.PSIsContainer } | Select-Object -ExpandProperty Name)
    $difference = @(Compare-Object -ReferenceObject $ExpectedFiles -DifferenceObject $actualFiles)
    if ($difference.Count -ne 0) {
        throw "Generated filename set differs in '$Directory': $($difference.InputObject -join ', ')"
    }

    foreach ($fileName in $ExpectedFiles) {
        $path = Join-Path $Directory $fileName
        if ((Get-Content -LiteralPath $path -TotalCount 1) -ne $generatedMarker) {
            throw "Generated file does not have the EF Core Power Tools ownership marker: $path"
        }

        if ($RequireCompiledMetadata -and -not (Select-String -LiteralPath $path -Pattern $generatedAttributePattern -Quiet)) {
            $observedMetadata = @(Get-Content -LiteralPath $path -TotalCount 16) -join ' | '
            throw "Generated file does not emit compiled generated-code metadata: $path. Observed: $observedMetadata"
        }
    }
}

function Assert-GeneratedBoundary {
    param(
        [Parameter(Mandatory = $false)]
        [string] $EntityDirectory = $script:entityDirectory,

        [Parameter(Mandatory = $false)]
        [string] $ContextDirectory = $script:contextDirectory,

        [Parameter(Mandatory = $false)]
        [switch] $RequireCompiledMetadata
    )

    Assert-ExactGeneratedDirectory -Directory $EntityDirectory -ExpectedFiles $expectedEntityFiles -RequireCompiledMetadata:$RequireCompiledMetadata
    Assert-ExactGeneratedDirectory -Directory $ContextDirectory -ExpectedFiles $expectedContextFiles -RequireCompiledMetadata:$RequireCompiledMetadata
}

function Remove-KnownReadmeByproduct {
    param(
        [Parameter(Mandatory = $false)]
        [string] $Path = $script:readmeByproduct
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return
    }

    if ((Get-Content -LiteralPath $Path -TotalCount 1).TrimEnd() -ne $readmeMarker) {
        throw "Refusing to remove an unrecognized file at the EFPT readme path: $Path"
    }

    Remove-Item -LiteralPath $Path -Force
}

function New-GeneratedBackup {
    param(
        [Parameter(Mandatory = $false)]
        [string] $SourceEntityDirectory = $script:entityDirectory,

        [Parameter(Mandatory = $false)]
        [string] $SourceContextDirectory = $script:contextDirectory
    )

    $temporaryRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath())
    $backupDirectory = Join-Path $temporaryRoot ("beacon-ar-efpt-backup-" + [System.Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path (Join-Path $backupDirectory 'Entities') -Force | Out-Null
    New-Item -ItemType Directory -Path (Join-Path $backupDirectory 'Context') -Force | Out-Null

    foreach ($fileName in $expectedEntityFiles) {
        Copy-Item -LiteralPath (Join-Path $SourceEntityDirectory $fileName) -Destination (Join-Path $backupDirectory 'Entities')
    }

    foreach ($fileName in $expectedContextFiles) {
        Copy-Item -LiteralPath (Join-Path $SourceContextDirectory $fileName) -Destination (Join-Path $backupDirectory 'Context')
    }

    return $backupDirectory
}

function Restore-GeneratedBackup {
    param(
        [Parameter(Mandatory = $true)]
        [string] $BackupDirectory,

        [Parameter(Mandatory = $false)]
        [string] $TargetEntityDirectory = $script:entityDirectory,

        [Parameter(Mandatory = $false)]
        [string] $TargetContextDirectory = $script:contextDirectory
    )

    foreach ($ownedDirectory in @($TargetEntityDirectory, $TargetContextDirectory)) {
        $ownedRoot = [System.IO.Path]::GetFullPath($ownedDirectory).TrimEnd([System.IO.Path]::DirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar
        foreach ($entry in @(Get-ChildItem -LiteralPath $ownedDirectory -Force)) {
            $entryPath = [System.IO.Path]::GetFullPath($entry.FullName)
            if (-not $entryPath.StartsWith($ownedRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
                throw "Refusing to restore outside the generated boundary: $entryPath"
            }

            Remove-Item -LiteralPath $entryPath -Recurse -Force
        }
    }

    foreach ($fileName in $expectedEntityFiles) {
        Copy-Item -LiteralPath (Join-Path $BackupDirectory "Entities/$fileName") -Destination $TargetEntityDirectory
    }

    foreach ($fileName in $expectedContextFiles) {
        Copy-Item -LiteralPath (Join-Path $BackupDirectory "Context/$fileName") -Destination $TargetContextDirectory
    }
}

function Remove-GeneratedBackup {
    param(
        [Parameter(Mandatory = $true)]
        [string] $BackupDirectory
    )

    $temporaryRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath()).TrimEnd([System.IO.Path]::DirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar
    $resolvedBackup = [System.IO.Path]::GetFullPath($BackupDirectory)
    if (-not $resolvedBackup.StartsWith($temporaryRoot, [System.StringComparison]::OrdinalIgnoreCase) -or
        -not ([System.IO.Path]::GetFileName($resolvedBackup)).StartsWith('beacon-ar-efpt-backup-', [System.StringComparison]::Ordinal)) {
        throw "Refusing to remove an unrecognized backup directory: $resolvedBackup"
    }

    if (Test-Path -LiteralPath $resolvedBackup -PathType Container) {
        Remove-Item -LiteralPath $resolvedBackup -Recurse -Force
    }
}

function Get-GeneratedHashes {
    param(
        [Parameter(Mandatory = $false)]
        [string] $EntityDirectory = $script:entityDirectory,

        [Parameter(Mandatory = $false)]
        [string] $ContextDirectory = $script:contextDirectory
    )

    $paths = @(
        $expectedEntityFiles | ForEach-Object { Join-Path $EntityDirectory $_ }
        $expectedContextFiles | ForEach-Object { Join-Path $ContextDirectory $_ }
    )

    return @($paths | Sort-Object | ForEach-Object { "$_|$((Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash)" })
}

function Remove-GuardedFixtureDirectory {
    param(
        [Parameter(Mandatory = $true)]
        [string] $Directory
    )

    $temporaryRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath()).TrimEnd([System.IO.Path]::DirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar
    $resolvedDirectory = [System.IO.Path]::GetFullPath($Directory)
    if (-not $resolvedDirectory.StartsWith($temporaryRoot, [System.StringComparison]::OrdinalIgnoreCase) -or
        -not ([System.IO.Path]::GetFileName($resolvedDirectory)).StartsWith('beacon-ar-efpt-fixture-', [System.StringComparison]::Ordinal)) {
        throw "Refusing to remove an unrecognized fixture directory: $resolvedDirectory"
    }

    if (Test-Path -LiteralPath $resolvedDirectory -PathType Container) {
        Remove-Item -LiteralPath $resolvedDirectory -Recurse -Force
    }
}

function Protect-SensitiveText {
    param(
        [Parameter(Mandatory = $true)]
        [string] $Text,

        [Parameter(Mandatory = $true)]
        [string] $SensitiveConnectionString
    )

    $redacted = $Text.Replace($SensitiveConnectionString, '[REDACTED CONNECTION STRING]')
    foreach ($segment in $SensitiveConnectionString.Split(';', [System.StringSplitOptions]::RemoveEmptyEntries)) {
        $parts = $segment.Split('=', 2)
        if ($parts.Count -ne 2 -or $parts[0].Trim() -notmatch '^(?i:password|pwd|user id|uid|access token)$') {
            continue
        }

        $sensitiveValue = $parts[1].Trim()
        if (-not [string]::IsNullOrEmpty($sensitiveValue)) {
            $redacted = $redacted.Replace($sensitiveValue, '[REDACTED]')
        }
    }

    return [System.Text.RegularExpressions.Regex]::Replace(
        $redacted,
        '(?i)(password|pwd|user id|uid|access token)\s*=\s*[^;\r\n]+',
        '$1=[REDACTED]')
}

function Invoke-FailureRecoveryFixture {
    $temporaryRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath())
    $fixtureRoot = Join-Path $temporaryRoot ("beacon-ar-efpt-fixture-" + [System.Guid]::NewGuid().ToString('N'))
    $fixtureEntityDirectory = Join-Path $fixtureRoot 'Entities'
    $fixtureContextDirectory = Join-Path $fixtureRoot 'Context'
    $fixtureReadme = Join-Path $fixtureRoot 'efcpt-readme.md'
    $backupDirectory = $null

    try {
        New-Item -ItemType Directory -Path $fixtureEntityDirectory -Force | Out-Null
        New-Item -ItemType Directory -Path $fixtureContextDirectory -Force | Out-Null
        foreach ($fileName in $expectedEntityFiles) {
            Copy-Item -LiteralPath (Join-Path $entityDirectory $fileName) -Destination $fixtureEntityDirectory
        }
        foreach ($fileName in $expectedContextFiles) {
            Copy-Item -LiteralPath (Join-Path $contextDirectory $fileName) -Destination $fixtureContextDirectory
        }
        [System.IO.File]::WriteAllText($fixtureReadme, "$readmeMarker`r`n")

        Assert-GeneratedBoundary -EntityDirectory $fixtureEntityDirectory -ContextDirectory $fixtureContextDirectory -RequireCompiledMetadata
        Remove-KnownReadmeByproduct -Path $fixtureReadme
        $beforeHashes = Get-GeneratedHashes -EntityDirectory $fixtureEntityDirectory -ContextDirectory $fixtureContextDirectory
        $backupDirectory = New-GeneratedBackup -SourceEntityDirectory $fixtureEntityDirectory -SourceContextDirectory $fixtureContextDirectory

        try {
            Add-Content -LiteralPath (Join-Path $fixtureEntityDirectory 'Product.cs') -Value '// intentional failure-recovery fixture mutation'
            [System.IO.File]::WriteAllText(
                (Join-Path $fixtureEntityDirectory 'Unexpected.cs'),
                "$generatedMarker`r`n[System.CodeDom.Compiler.GeneratedCode(`"EFCorePowerTools`", `"10.1.1386`")]`r`npublic sealed class Unexpected { }`r`n")
            throw 'Intentional EFPT generation failure fixture.'
        }
        catch {
            if ($_.Exception.Message -ne 'Intentional EFPT generation failure fixture.') {
                throw
            }

            Restore-GeneratedBackup -BackupDirectory $backupDirectory -TargetEntityDirectory $fixtureEntityDirectory -TargetContextDirectory $fixtureContextDirectory
        }

        Assert-GeneratedBoundary -EntityDirectory $fixtureEntityDirectory -ContextDirectory $fixtureContextDirectory -RequireCompiledMetadata
        $afterHashes = Get-GeneratedHashes -EntityDirectory $fixtureEntityDirectory -ContextDirectory $fixtureContextDirectory
        if ((Compare-Object -ReferenceObject $beforeHashes -DifferenceObject $afterHashes).Count -ne 0) {
            throw 'Failure recovery changed the temporary generated-output fixture.'
        }
    }
    finally {
        if (-not [string]::IsNullOrEmpty($backupDirectory)) {
            Remove-GeneratedBackup -BackupDirectory $backupDirectory
        }
        Remove-GuardedFixtureDirectory -Directory $fixtureRoot
    }

    Write-Host 'EFPT failure recovery fixture passed entirely within a guarded temporary copy.'
}

function Invoke-RedactionFixture {
    $sentinelPassword = 'BeaconSentinelPassword-937!'
    $sentinelUser = 'BeaconSentinelUser-937'
    $sentinelConnection = "Server=fixture.invalid;Database=Fixture;User ID=$sentinelUser;Password=$sentinelPassword;Encrypt=True"
    $simulatedLog = "System.Exception: failed for $sentinelConnection`r`nPassword=$sentinelPassword; User ID=$sentinelUser"
    $redactedLog = Protect-SensitiveText -Text $simulatedLog -SensitiveConnectionString $sentinelConnection

    if ($redactedLog.IndexOf($sentinelConnection, [System.StringComparison]::Ordinal) -ge 0 -or
        $redactedLog.IndexOf($sentinelPassword, [System.StringComparison]::Ordinal) -ge 0 -or
        $redactedLog.IndexOf($sentinelUser, [System.StringComparison]::Ordinal) -ge 0) {
        throw 'Connection-string redaction fixture failed.'
    }

    Write-Host 'EFPT error redaction fixture passed without disclosing sentinel credentials.'
}

foreach ($requiredFile in @($config, $contextTemplate, $entityTemplate, $toolManifest)) {
    if (-not (Test-Path -LiteralPath $requiredFile -PathType Leaf)) {
        throw "Required generation input is missing: $requiredFile"
    }
}

$manifest = Get-Content -LiteralPath $toolManifest -Raw | ConvertFrom-Json
$efcptTool = $manifest.tools.'erikej.efcorepowertools.cli'
if ($null -eq $efcptTool -or $efcptTool.version -ne '10.1.1386' -or 'efcpt' -notin $efcptTool.commands) {
    throw 'The local tool manifest must pin ErikEJ.EFCorePowerTools.Cli 10.1.1386 with the efcpt command.'
}

if ($null -ne $manifest.tools.'dotnet-ef') {
    throw 'The legacy dotnet-ef tool must not be present in the example-local manifest.'
}

$configText = Get-Content -LiteralPath $config -Raw
if ($configText -match '(?i)connection(string)?|password|user id|server=') {
    throw 'efcpt-config.json must not contain a connection string or credentials.'
}

if ($TestFailureRecovery -or $TestRedaction) {
    if ($TestFailureRecovery) {
        Assert-GeneratedBoundary -RequireCompiledMetadata
        Invoke-FailureRecoveryFixture
    }
    if ($TestRedaction) {
        Invoke-RedactionFixture
    }

    return
}

Assert-GeneratedBoundary
Remove-KnownReadmeByproduct

if ([string]::IsNullOrWhiteSpace($ConnectionString)) {
    throw 'ConnectionStrings__DatabaseConnection is required for EF Core Power Tools generation.'
}

Push-Location $dataDirectory
try {
    dotnet tool restore
    if ($LASTEXITCODE -ne 0) { throw 'Local tool restore failed.' }

    dotnet build $solution --configuration Release
    if ($LASTEXITCODE -ne 0) { throw 'The solution must build before replacing generated persistence output.' }

    $backupDirectory = New-GeneratedBackup
    try {
        $generationOutput = & dotnet tool run efcpt -- $ConnectionString mssql `
            --input $config `
            --output $dataDirectory `
            --verbose 2>&1 | Tee-Object -Variable generationLog
        $safeGenerationLog = Protect-SensitiveText `
            -Text ([string]($generationLog -join [Environment]::NewLine)) `
            -SensitiveConnectionString $ConnectionString
        Write-Verbose $safeGenerationLog
        if ($LASTEXITCODE -ne 0 -or ($generationLog -join "`n") -match '(?im)^error:') {
            $safeErrors = @(($safeGenerationLog -split '\r?\n') | Where-Object { $_ -match '(?i)error|failed|exception' }) -join [Environment]::NewLine
            throw "EF Core Power Tools generation failed.$([Environment]::NewLine)$safeErrors"
        }

        Remove-KnownReadmeByproduct
        Assert-GeneratedBoundary -RequireCompiledMetadata

        dotnet build $solution --configuration Release --no-restore
        if ($LASTEXITCODE -ne 0) { throw 'Generated persistence output does not compile.' }
    }
    catch {
        $safeFailureMessage = Protect-SensitiveText -Text $_.Exception.Message -SensitiveConnectionString $ConnectionString
        Restore-GeneratedBackup -BackupDirectory $backupDirectory
        Remove-KnownReadmeByproduct
        Assert-GeneratedBoundary
        throw $safeFailureMessage
    }
    finally {
        Remove-GeneratedBackup -BackupDirectory $backupDirectory
    }
}
finally {
    Pop-Location
}
