[CmdletBinding()]
param(
    [string] $ConnectionString = $env:ConnectionStrings__DatabaseConnection,
    [switch] $TestFailureRecovery,
    [switch] $TestLiveFailureRecovery,
    [switch] $TestRedaction
)

$ErrorActionPreference = 'Stop'
$exampleRoot = Split-Path -Parent $PSScriptRoot
$solution = Join-Path $exampleRoot 'BeaconAr.slnx'
$dataRoot = Join-Path $exampleRoot 'src/BeaconAr.Data'
$domainRoot = Join-Path $exampleRoot 'src/BeaconAr.Domain'
$toolManifest = Join-Path $exampleRoot '.config/dotnet-tools.json'
$generatedMarker = '// <auto-generated> This file has been auto generated by EF Core Power Tools. </auto-generated>'
$readmeByproduct = Join-Path $dataRoot 'efcpt-readme.md'
$readmeMarker = "Congratulations, 'EF Core Power Tools' has now generated a DbContext and Entity classes for you."
$boundaries = [ordered]@{
    Access = @('ApplicationUser.cs', 'ApplicationUserView.cs')
    MasterData = @('AddressType.cs', 'Carrier.cs', 'CarrierView.cs', 'Customer.cs', 'CustomerAddress.cs', 'CustomerAddressView.cs', 'CustomerView.cs', 'Product.cs', 'ProductView.cs')
    Operations = @('AuditLog.cs', 'AuditLogView.cs', 'IdempotencyRequest.cs', 'IdempotencyRequestView.cs', 'IdempotencyState.cs', 'IdempotencyStateView.cs')
    Sales = @('Quote.cs', 'QuoteLine.cs', 'QuoteLineView.cs', 'QuotePricingView.cs', 'QuoteStatus.cs', 'QuoteStatusHistory.cs', 'QuoteView.cs', 'SalesOrder.cs', 'SalesOrderLine.cs', 'SalesOrderLineView.cs', 'SalesOrderPricingView.cs', 'SalesOrderStatus.cs', 'SalesOrderStatusHistory.cs', 'SalesOrderView.cs')
}
$handwrittenPartials = @(
    'src/BeaconAr.Domain/Access/Entities/ApplicationUser.Behavior.cs'
    'src/BeaconAr.Domain/MasterData/Entities/Carrier.Behavior.cs'
    'src/BeaconAr.Domain/MasterData/Entities/Customer.Behavior.cs'
    'src/BeaconAr.Domain/MasterData/Entities/CustomerAddress.Behavior.cs'
    'src/BeaconAr.Domain/MasterData/Entities/Product.Behavior.cs'
    'src/BeaconAr.Domain/Operations/Entities/IdempotencyRequest.Behavior.cs'
    'src/BeaconAr.Domain/Operations/Entities/AuditLog.Behavior.cs'
    'src/BeaconAr.Domain/Sales/Entities/Quote.Behavior.cs'
    'src/BeaconAr.Domain/Sales/Entities/QuoteLine.Behavior.cs'
    'src/BeaconAr.Domain/Sales/Entities/QuoteStatusHistory.Behavior.cs'
    'src/BeaconAr.Domain/Sales/Entities/SalesOrder.Behavior.cs'
    'src/BeaconAr.Domain/Sales/Entities/SalesOrderLine.Behavior.cs'
    'src/BeaconAr.Domain/Sales/Entities/SalesOrderStatusHistory.Behavior.cs'
    'src/BeaconAr.Data/MasterData/Context/MasterDataDbContext.Relationships.cs'
)

function Get-OwnedPaths {
    $paths = @()
    foreach ($entry in $boundaries.GetEnumerator()) {
        $capability = $entry.Key
        $paths += $entry.Value | ForEach-Object { Join-Path $domainRoot "$capability/Entities/$_" }
        $paths += Join-Path $dataRoot "$capability/Context/${capability}DbContext.cs"
    }
    return $paths
}

function Get-HandwrittenPartialPaths {
    return @($handwrittenPartials | ForEach-Object { [IO.Path]::GetFullPath((Join-Path $exampleRoot $_)) })
}

function Get-ProtectedPaths {
    return @((@(Get-OwnedPaths) + @(Get-HandwrittenPartialPaths)) | ForEach-Object { [IO.Path]::GetFullPath($_) } | Sort-Object -Unique)
}

function Get-ProtectedHashes {
    return @(Get-ProtectedPaths | ForEach-Object {
        if (-not (Test-Path -LiteralPath $_ -PathType Leaf)) { throw "Protected persistence file is missing: $_" }
        "$_|$((Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash)"
    })
}

function Get-RecognizedGeneratorPaths {
    $paths = @()
    foreach ($root in @($dataRoot, $domainRoot)) {
        $paths += Get-ChildItem $root -Recurse -File -Filter *.cs | Where-Object {
            (Get-Content -LiteralPath $_.FullName -TotalCount 1) -eq $generatedMarker
        } | ForEach-Object FullName
    }
    if ((Test-Path -LiteralPath $readmeByproduct -PathType Leaf) -and
        (Get-Content -LiteralPath $readmeByproduct -TotalCount 1).TrimEnd() -eq $readmeMarker) {
        $paths += $readmeByproduct
    }
    return @($paths | ForEach-Object { [IO.Path]::GetFullPath($_) } | Sort-Object -Unique)
}

function Get-RecognizedGeneratorHashes {
    return @(Get-RecognizedGeneratorPaths | ForEach-Object { "$_|$((Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash)" })
}

function Get-RecoveryFingerprint {
    $state = (@(Get-ProtectedHashes) + @(Get-RecognizedGeneratorHashes) | Sort-Object) -join "`n"
    $algorithm = [Security.Cryptography.SHA256]::Create()
    try {
        return ([BitConverter]::ToString($algorithm.ComputeHash([Text.Encoding]::UTF8.GetBytes($state)))).Replace('-', '')
    }
    finally { $algorithm.Dispose() }
}

function Assert-Inputs {
    $manifest = Get-Content -LiteralPath $toolManifest -Raw | ConvertFrom-Json
    $tool = $manifest.tools.'erikej.efcorepowertools.cli'
    if ($null -eq $tool -or $tool.version -ne '10.1.1386' -or 'efcpt' -notin $tool.commands) {
        throw 'The local EF Core Power Tools CLI must remain pinned to 10.1.1386.'
    }

    foreach ($template in @('DbContext.t4', 'EntityType.t4', 'PROVENANCE.md')) {
        if (-not (Test-Path -LiteralPath (Join-Path $dataRoot "CodeTemplates/EFCore/$template") -PathType Leaf)) {
            throw "Official-derived template input is missing: $template"
        }
    }

    $selected = @()
    foreach ($capability in $boundaries.Keys) {
        $configPath = Join-Path $dataRoot ("efcpt-{0}-config.json" -f $capability.ToLowerInvariant())
        if (-not (Test-Path -LiteralPath $configPath -PathType Leaf)) { throw "Missing EFPT config: $configPath" }
        $text = Get-Content -LiteralPath $configPath -Raw
        if ($text -match '(?i)connection(string)?|password|user id|server=') { throw "Credentials are forbidden in $configPath" }
        $config = $text | ConvertFrom-Json
        if ($config.names.'dbcontext-name' -ne "${capability}DbContext" -or
            $config.names.'dbcontext-namespace' -ne "BeaconAr.Data.$capability.Context" -or
            $config.names.'model-namespace' -ne "BeaconAr.Domain.$capability.Entities") {
            throw "EFPT namespace ownership is invalid in $configPath"
        }
        $selected += @($config.tables.name)
        $selected += @($config.views.name)
    }
    if ($selected.Count -ne 31 -or @($selected | Select-Object -Unique).Count -ne 31) {
        throw 'The four EFPT selections must be disjoint and contain exactly 17 tables plus 14 views.'
    }

    $expectedPartials = @(Get-HandwrittenPartialPaths | Sort-Object)
    $discoveredPartials = @(
        @(Get-ChildItem $domainRoot -Recurse -Filter *.Behavior.cs | ForEach-Object { [IO.Path]::GetFullPath($_.FullName) }) +
        @([IO.Path]::GetFullPath((Join-Path $dataRoot 'MasterData/Context/MasterDataDbContext.Relationships.cs'))) |
        Sort-Object -Unique
    )
    if (Compare-Object $expectedPartials $discoveredPartials) {
        throw 'The exact handwritten persistence partial manifest is incomplete or stale.'
    }
}

function Assert-GeneratedBoundary {
    foreach ($path in Get-OwnedPaths) {
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Missing generated output: $path" }
        if ((Get-Content -LiteralPath $path -TotalCount 1) -ne $generatedMarker) { throw "Invalid ownership marker: $path" }
        if (-not (Select-String -LiteralPath $path -Pattern 'GeneratedCode(?:Attribute)?\("EFCorePowerTools", "10\.1\.1386"\)' -Quiet)) {
            throw "Missing compiled generated-code metadata: $path"
        }
    }

    $owned = @(Get-OwnedPaths | ForEach-Object { [IO.Path]::GetFullPath($_) })
    $unexpected = @($dataRoot, $domainRoot) | ForEach-Object {
        Get-ChildItem $_ -Recurse -Filter *.cs | Where-Object {
            (Get-Content -LiteralPath $_.FullName -TotalCount 1) -eq $generatedMarker -and
            [IO.Path]::GetFullPath($_.FullName) -notin $owned
        }
    }
    if ($unexpected) { throw "Unexpected generated files: $($unexpected.FullName -join ', ')" }
}

function Get-Hashes {
    return @(Get-OwnedPaths | Sort-Object | ForEach-Object { "$_|$((Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash)" })
}

function Get-RelativeOwnedPath([string] $Path) {
    $root = [IO.Path]::GetFullPath($exampleRoot).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    $resolved = [IO.Path]::GetFullPath($Path)
    if (-not $resolved.StartsWith($root, [StringComparison]::OrdinalIgnoreCase)) { throw "Path is outside the example root: $resolved" }
    return $resolved.Substring($root.Length)
}

function Protect-SensitiveText([string] $Text, [string] $SensitiveConnectionString) {
    $safe = $Text.Replace($SensitiveConnectionString, '[REDACTED CONNECTION STRING]')
    return [regex]::Replace($safe, '(?i)(password|pwd|user id|uid|access token)\s*=\s*[^;\r\n]+', '$1=[REDACTED]')
}

function Remove-KnownReadme {
    if (-not (Test-Path -LiteralPath $readmeByproduct)) { return }
    if ((Get-Content -LiteralPath $readmeByproduct -TotalCount 1).TrimEnd() -ne $readmeMarker) {
        throw "Refusing to remove an unrecognized EFPT byproduct: $readmeByproduct"
    }
    Remove-Item -LiteralPath $readmeByproduct
}

function New-Backup([string[]] $Paths) {
    $backup = Join-Path ([IO.Path]::GetTempPath()) ("beacon-ar-efpt-backup-" + [Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $backup | Out-Null
    foreach ($path in $Paths) {
        $relative = Get-RelativeOwnedPath $path
        $target = Join-Path $backup $relative
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
        Copy-Item -LiteralPath $path -Destination $target
    }
    return $backup
}

function Restore-Backup([string] $Backup, [string[]] $Paths) {
    foreach ($path in $Paths) {
        $source = Join-Path $Backup (Get-RelativeOwnedPath $path)
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
        Copy-Item -LiteralPath $source -Destination $path -Force
    }
}

function Remove-NewRecognizedOutputs([string[]] $BeforePaths) {
    $before = @($BeforePaths | ForEach-Object { [IO.Path]::GetFullPath($_) })
    foreach ($path in Get-RecognizedGeneratorPaths) {
        if ($path -in $before) { continue }
        $dataPrefix = [IO.Path]::GetFullPath($dataRoot).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
        $domainPrefix = [IO.Path]::GetFullPath($domainRoot).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
        if (-not $path.StartsWith($dataPrefix, [StringComparison]::OrdinalIgnoreCase) -and
            -not $path.StartsWith($domainPrefix, [StringComparison]::OrdinalIgnoreCase)) {
            throw "Refusing to remove recognized output outside persistence roots: $path"
        }
        Remove-Item -LiteralPath $path -Force
    }
}

function Invoke-RecoverableWorkflow([scriptblock] $Action) {
    $beforeHashes = Get-ProtectedHashes
    $beforePartialHashes = @(Get-HandwrittenPartialPaths | ForEach-Object { "$_|$((Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash)" })
    $beforeRecognized = @(Get-RecognizedGeneratorPaths)
    $beforeRecognizedHashes = @(Get-RecognizedGeneratorHashes)
    $backupPaths = @(@(Get-ProtectedPaths) + $beforeRecognized | Sort-Object -Unique)
    $backup = New-Backup $backupPaths
    try {
        & $Action
        $afterPartialHashes = @(Get-HandwrittenPartialPaths | ForEach-Object { "$_|$((Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash)" })
        if (Compare-Object $beforePartialHashes $afterPartialHashes) {
            throw 'Persistence generation changed a handwritten entity or context partial.'
        }
    }
    catch {
        Remove-NewRecognizedOutputs $beforeRecognized
        Restore-Backup $backup $backupPaths
        if (Compare-Object $beforeHashes (Get-ProtectedHashes)) {
            throw 'Persistence recovery did not restore every generated file and handwritten partial.'
        }
        if (Compare-Object $beforeRecognized (Get-RecognizedGeneratorPaths)) {
            throw 'Persistence recovery did not restore the recognized generated/byproduct path set.'
        }
        if (Compare-Object $beforeRecognizedHashes (Get-RecognizedGeneratorHashes)) {
            throw 'Persistence recovery did not restore the recognized generated/byproduct hashes.'
        }
        throw
    }
    finally { Remove-Backup $backup }
}

function Remove-Backup([string] $Backup) {
    $tempRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    $resolved = [IO.Path]::GetFullPath($Backup)
    if (-not $resolved.StartsWith($tempRoot, [StringComparison]::OrdinalIgnoreCase) -or
        -not [IO.Path]::GetFileName($resolved).StartsWith('beacon-ar-efpt-backup-', [StringComparison]::Ordinal)) {
        throw "Refusing to remove unrecognized backup: $resolved"
    }
    Remove-Item -LiteralPath $resolved -Recurse -Force
}

function Invoke-CapabilityGeneration([string] $Capability) {
    if ($Capability -notin $boundaries.Keys) { throw "Unknown persistence capability: $Capability" }
    $config = Join-Path $dataRoot ("efcpt-{0}-config.json" -f $Capability.ToLowerInvariant())
    $output = & dotnet tool run efcpt -- $ConnectionString mssql --input $config --output $dataRoot --verbose 2>&1
    if ($LASTEXITCODE -ne 0 -or ($output -join "`n") -match '(?im)^error:') {
        throw (Protect-SensitiveText ($output -join [Environment]::NewLine) $ConnectionString)
    }
    Remove-KnownReadme
}

function Invoke-GenerationPass {
    foreach ($capability in $boundaries.Keys) { Invoke-CapabilityGeneration $capability }
    Assert-GeneratedBoundary
}

Assert-Inputs
Assert-GeneratedBoundary

if ($TestRedaction) {
    $secret = 'Server=fixture.invalid;User ID=sentinel-user;Password=sentinel-password'
    $safe = Protect-SensitiveText "failed: $secret" $secret
    if ($safe.Contains('sentinel-user') -or $safe.Contains('sentinel-password')) { throw 'Redaction fixture failed.' }
    Write-Host 'EFPT redaction fixture passed.'
}

if ($TestFailureRecovery) {
    $beforeFingerprint = Get-RecoveryFingerprint
    $fixtureFailed = $false
    try {
        Invoke-RecoverableWorkflow {
            Add-Content -LiteralPath (Join-Path $dataRoot 'Access/Context/AccessDbContext.cs') -Value '// simulated EFPT boundary output'
            Add-Content -LiteralPath (Get-HandwrittenPartialPaths | Select-Object -First 1) -Value '// injected protected partial mutation'
            $unexpected = Join-Path $domainRoot 'Access/Entities/InjectedFailureGenerated.cs'
            Set-Content -LiteralPath $unexpected -Value @($generatedMarker, '[System.CodeDom.Compiler.GeneratedCode("EFCorePowerTools", "10.1.1386")]', 'internal sealed class InjectedFailureGenerated {}')
            Set-Content -LiteralPath $readmeByproduct -Value @($readmeMarker, 'fixture')
            throw 'Injected failure after generated and protected persistence mutations.'
        }
    }
    catch {
        if ($_.Exception.Message -ne 'Injected failure after generated and protected persistence mutations.') { throw }
        $fixtureFailed = $true
    }
    if (-not $fixtureFailed) { throw 'Failure recovery fixture did not inject the expected boundary failure.' }
    $afterFingerprint = Get-RecoveryFingerprint
    if ($beforeFingerprint -ne $afterFingerprint) { throw 'Fast failure recovery did not restore complete path/hash parity.' }
    Write-Host "EFPT fast protected-boundary recovery fixture passed. State SHA256: $afterFingerprint"
}

if ($TestFailureRecovery -or $TestRedaction) {
    if (-not $TestLiveFailureRecovery) { return }
}
if ([string]::IsNullOrWhiteSpace($ConnectionString)) { throw 'ConnectionStrings__DatabaseConnection is required.' }

Push-Location $dataRoot
try {
    dotnet tool restore
    if ($LASTEXITCODE -ne 0) { throw 'Local tool restore failed.' }
    if ($TestLiveFailureRecovery) {
        $beforeFingerprint = Get-RecoveryFingerprint
        $fixtureFailed = $false
        try {
            Invoke-RecoverableWorkflow {
                Invoke-CapabilityGeneration 'Access'
                throw 'Injected live failure after Access EFPT generation and before MasterData.'
            }
        }
        catch {
            if ($_.Exception.Message -ne 'Injected live failure after Access EFPT generation and before MasterData.') { throw }
            $fixtureFailed = $true
        }
        if (-not $fixtureFailed) { throw 'Live failure recovery fixture did not inject the expected boundary failure.' }
        $afterFingerprint = Get-RecoveryFingerprint
        if ($beforeFingerprint -ne $afterFingerprint) { throw 'Live EFPT failure recovery did not restore complete path/hash parity.' }
        Write-Host "EFPT live Access-boundary recovery fixture passed. State SHA256: $afterFingerprint"
        return
    }
    Invoke-RecoverableWorkflow {
        Invoke-GenerationPass
        dotnet build $solution --configuration Release --no-restore
        if ($LASTEXITCODE -ne 0) { throw 'First generated pass does not compile.' }
        $first = Get-Hashes
        Invoke-GenerationPass
        if (Compare-Object $first (Get-Hashes)) { throw 'EFPT generation is not byte-stable across two passes.' }
    }
}
finally { Pop-Location }
