        };
        var all = new List<string>();
        foreach ((string capability, string[] objects) in expected)
        {
            string config = Path.Combine(dataRoot, $"efcpt-{capability.ToLowerInvariant()}-config.json");
            using JsonDocument document = JsonDocument.Parse(File.ReadAllText(config));
            string[] actual = document.RootElement.GetProperty("tables").EnumerateArray()
                .Concat(document.RootElement.GetProperty("views").EnumerateArray())
                .Select(item => item.GetProperty("name").GetString()!).ToArray();
            CollectionAssert.AreEqual(objects, actual, capability);
            all.AddRange(actual);
        }
        Assert.HasCount(17, all.Where(name => !name.EndsWith("View]", StringComparison.Ordinal)).ToArray());
        Assert.HasCount(14, all.Where(name => name.EndsWith("View]", StringComparison.Ordinal)).ToArray());
        Assert.HasCount(31, all.Distinct(StringComparer.Ordinal).ToArray());
    }

