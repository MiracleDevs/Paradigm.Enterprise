        {
            ["Access"] = ["[dbo].[ApplicationUser]", "[dbo].[ApplicationUserView]"],
            ["MasterData"] = ["[dbo].[AddressType]", "[dbo].[Carrier]", "[dbo].[Customer]", "[dbo].[CustomerAddress]", "[dbo].[Product]", "[dbo].[CarrierView]", "[dbo].[CustomerView]", "[dbo].[CustomerAddressView]", "[dbo].[ProductView]"],
