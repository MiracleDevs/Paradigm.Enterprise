    private static string[] MapperPaths(string dataRoot) => Directory.GetFiles(dataRoot, "*.cs", SearchOption.AllDirectories)
        .Where(path => path.Contains($"{Path.DirectorySeparatorChar}Mappers{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
        .Select(path => Path.GetRelativePath(dataRoot, path).Replace('\\', '/')).Order(StringComparer.Ordinal).ToArray();

    private static string[] HashFiles(string dataRoot, IEnumerable<string> paths) => paths
        .Select(path => $"{path}|{Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(Path.Combine(dataRoot, path))))}")
        .Order(StringComparer.Ordinal).ToArray();

    private static void RunProcess(string workingDirectory, string fileName, params string[] arguments)
    {
        using var process = Process.Start(new ProcessStartInfo(fileName, arguments)
        {
            WorkingDirectory = workingDirectory,
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
        }) ?? throw new InvalidOperationException($"Could not start {fileName}.");
        string output = process.StandardOutput.ReadToEnd();
        string error = process.StandardError.ReadToEnd();
        Assert.IsTrue(process.WaitForExit(120_000), $"{fileName} timed out.");
        Assert.AreEqual(0, process.ExitCode, $"{fileName} failed:{Environment.NewLine}{output}{Environment.NewLine}{error}");
    }

    private static TContext Create<TContext>() where TContext : DbContext
    {
        var services = new Microsoft.Extensions.DependencyInjection.ServiceCollection().BuildServiceProvider();
        return (TContext)Activator.CreateInstance(typeof(TContext), services,
            new DbContextOptionsBuilder<TContext>().UseSqlServer("Server=(localdb)\\MSSQLLocalDB;Database=BeaconArMetadata;Trusted_Connection=True").Options)!;
    }

    private static string FindExampleRoot()
    {
        DirectoryInfo? directory = new(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "BeaconAr.slnx")))
            directory = directory.Parent;
        return directory?.FullName ?? throw new DirectoryNotFoundException("Beacon AR example root was not found.");
    }

