    [TestMethod]
    public void ContextNavigationMatrixIsExact()
    {
        Dictionary<Type, string[]> expected = new()
        {
            [typeof(ApplicationUser)] = ["CreatedByUser", "InverseCreatedByUser", "InverseModifiedByUser", "ModifiedByUser"],
            [typeof(AddressType)] = ["CustomerAddresses"], [typeof(Customer)] = ["CustomerAddresses"],
            [typeof(CustomerAddress)] = ["AddressType", "Customer"], [typeof(IdempotencyRequest)] = ["State"],
            [typeof(IdempotencyState)] = ["IdempotencyRequests"],
            [typeof(Quote)] = ["QuoteLines", "QuoteStatusHistories", "SalesOrder", "Status"],
            [typeof(QuoteLine)] = ["Quote"], [typeof(QuoteStatus)] = ["Quotes", "QuoteStatusHistories"],
            [typeof(QuoteStatusHistory)] = ["Quote", "Status"],
            [typeof(SalesOrder)] = ["SalesOrderLines", "SalesOrderStatusHistories", "SourceQuote", "Status"],
            [typeof(SalesOrderLine)] = ["SalesOrder"], [typeof(SalesOrderStatus)] = ["SalesOrders", "SalesOrderStatusHistories"],
            [typeof(SalesOrderStatusHistory)] = ["SalesOrder", "Status"],
        };
        DbContext[] contexts = [Create<AccessDbContext>(), Create<MasterDataDbContext>(), Create<OperationsDbContext>(), Create<SalesDbContext>()];
        try
        {
            Dictionary<Type, string[]> actual = contexts.SelectMany(context => context.Model.GetEntityTypes())
                .Where(entity => !entity.ClrType.Name.EndsWith("View", StringComparison.Ordinal))
                .ToDictionary(entity => entity.ClrType, entity => entity.GetNavigations().Select(navigation => navigation.Name).Order(StringComparer.Ordinal).ToArray());
            foreach ((Type type, string[] navigations) in expected)
                CollectionAssert.AreEqual(navigations.Order(StringComparer.Ordinal).ToArray(), actual[type], type.FullName);
            foreach ((Type type, string[] navigations) in actual.Where(pair => !expected.ContainsKey(pair.Key)))
                Assert.HasCount(0, navigations, type.FullName);
        }
        finally
        {
            foreach (DbContext context in contexts)
                context.Dispose();
        }
    }

    [TestMethod]
    public void MapperInventoryRegistrationDeterminismAndFailureRecoveryAreExact()
    {
        string root = FindExampleRoot();
        string dataRoot = Path.Combine(root, "src", "BeaconAr.Data");
        string[] expected = MapperManifest();
        CollectionAssert.AreEqual(expected, MapperPaths(dataRoot));
        foreach (string capability in new[] { "Access", "MasterData", "Operations", "Sales" })
        {
            string mapperRoot = Path.Combine(dataRoot, capability, "Mappers");
            string registrar = File.ReadAllText(Path.Combine(mapperRoot, $"{capability}StoredProcedureMappersRegisterer.cs"));
            foreach (string mapper in expected.Where(path => path.StartsWith($"{capability}/Mappers/", StringComparison.Ordinal) && !path.EndsWith("Registerer.cs", StringComparison.Ordinal)))
                StringAssert.Contains(registrar, $"new {(mapper.Contains("/DataReaders/", StringComparison.Ordinal) ? "DataReaders" : "SqlParameters")}.{Path.GetFileNameWithoutExtension(mapper)}()");
        }
        string module = File.ReadAllText(Path.Combine(dataRoot, "StoredProcedureMapperRegistration.cs"));
        foreach (string capability in new[] { "Access", "MasterData", "Operations", "Sales" })
            StringAssert.Contains(module, $"{capability}StoredProcedureMappersRegisterer.RegisterMappers()");
        Assert.IsFalse(Directory.Exists(Path.Combine(dataRoot, "Mappers")));

        string[] before = HashFiles(dataRoot, expected);
        RunProcess(root, "dotnet", "run", "--project", "src/BeaconAr.CodeGenerator/BeaconAr.CodeGenerator.csproj", "--configuration", "Release", "--no-build", "--", "mappers");
        string[] first = HashFiles(dataRoot, expected);
        RunProcess(root, "dotnet", "run", "--project", "src/BeaconAr.CodeGenerator/BeaconAr.CodeGenerator.csproj", "--configuration", "Release", "--no-build", "--", "mappers");
        CollectionAssert.AreEqual(first, HashFiles(dataRoot, expected));
        CollectionAssert.AreEqual(before, first);

        string target = Path.Combine(dataRoot, "Access", "Mappers");
        string[] targetBefore = Directory.GetFiles(target, "*", SearchOption.AllDirectories).Select(path => $"{path}|{Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(path)))}").Order(StringComparer.Ordinal).ToArray();
        using (var output = new BeaconAr.CodeGenerator.AtomicOutputDirectory(target))
            File.WriteAllText(Path.Combine(output.Path, "InjectedFailure.cs"), "failure");
        string[] targetAfter = Directory.GetFiles(target, "*", SearchOption.AllDirectories).Select(path => $"{path}|{Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(path)))}").Order(StringComparer.Ordinal).ToArray();
        CollectionAssert.AreEqual(targetBefore, targetAfter);
        Assert.HasCount(0, Directory.GetDirectories(Path.GetDirectoryName(target)!, ".Mappers.staging-*"));
    }

