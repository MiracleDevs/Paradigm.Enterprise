    [TestMethod]
    public void GeneratedPersistenceBoundaryRepresentsTheFoundationSchema()
    {
        var root = FindExampleRoot();
        var entityDirectory = Path.Combine(root, "src", "BeaconAr.Domain", "Receivables", "Generated");
        var entityFiles = Directory.GetFiles(entityDirectory, "*.cs", SearchOption.TopDirectoryOnly);
        var context = File.ReadAllText(Path.Combine(root, "src", "BeaconAr.Data", "Receivables", "Generated", "ReceivablesDbContext.cs"));

        Assert.HasCount(19, entityFiles);
        Assert.AreEqual(19, CountOccurrences(context, "DbSet<"));
        Assert.AreEqual(6, CountOccurrences(context, ".IsRowVersion()"));
        Assert.AreEqual(2, CountOccurrences(context, ".HasNoKey()"));
        StringAssert.Contains(context, ".HasForeignKey(d => new { d.CustomerId, d.ShippingAddressId })");
        StringAssert.Contains(context, ".HasComputedColumnSql(");
        Assert.IsFalse(context.Contains("Server=", StringComparison.OrdinalIgnoreCase));
        Assert.IsTrue(entityFiles.All(path => File.ReadLines(path).First() == "// <auto-generated/>"));
    }

    [TestMethod]
    public void CustomerAddressOwnershipMetadataIsOneToMany()
    {
        var options = new DbContextOptionsBuilder<ReceivablesDbContext>()
            .UseSqlServer("Server=metadata-only;Initial Catalog=BeaconAr;Integrated Security=True;Encrypt=True")
            .Options;
        using var context = new ReceivablesDbContext(EmptyServiceProvider.Instance, options);

        var entityType = context.Model.FindEntityType(typeof(CustomerAddress));
        Assert.IsNotNull(entityType);
        var relationship = entityType.GetForeignKeys().Single(foreignKey => foreignKey.GetConstraintName() == "FK_CustomerAddress_Customer");
        Assert.IsFalse(relationship.IsUnique);
        Assert.IsNotNull(relationship.PrincipalToDependent);
        Assert.IsTrue(relationship.PrincipalToDependent.IsCollection);
        Assert.AreEqual("CustomerAddresses", relationship.PrincipalToDependent.Name);
        foreach (var indexName in new[] { "UQ_CustomerAddress_CustomerId_DefaultBilling", "UQ_CustomerAddress_CustomerId_DefaultShipping" })
        {
            var filteredIndex = entityType.GetIndexes().Single(index => index.GetDatabaseName() == indexName);
            Assert.IsTrue(filteredIndex.IsUnique);
            Assert.IsFalse(string.IsNullOrWhiteSpace(filteredIndex.GetFilter()));
        }

        var customer = new Customer();
        context.AddRange(
            new CustomerAddress { Customer = customer },
            new CustomerAddress { Customer = customer });
        var addresses = relationship.PrincipalToDependent.PropertyInfo?.GetValue(customer) as ICollection<CustomerAddress>;
        Assert.IsNotNull(addresses);
        Assert.HasCount(2, addresses);
    }

