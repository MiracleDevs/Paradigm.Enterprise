    #region Private Methods

    private static void AssertReferences(string root, string project, params string[] expected)
    {
        var document = XDocument.Load(Path.Combine(root, "src", project, $"{project}.csproj"));
        var references = document.Descendants("ProjectReference")
            .Select(static item => Path.GetFileNameWithoutExtension(item.Attribute("Include")?.Value))
            .Where(static item => item is not null)
            .ToArray();
        CollectionAssert.AreEquivalent(expected, references!);
    }

    private static int CountOccurrences(string text, string value) =>
        (text.Length - text.Replace(value, string.Empty, StringComparison.Ordinal).Length) / value.Length;

    private static string FindExampleRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "aspire.config.json")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName ?? throw new DirectoryNotFoundException("Beacon AR example root not found.");
    }

    #endregion
