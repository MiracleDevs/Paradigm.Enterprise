using System.Reflection;
using System.Text;

namespace Paradigm.Enterprise.CodeGenerator.Generators;

internal static class ParameterMapperSourceGenerator
{
    #region Public Methods

    public static string Generate(Type type, string projectName, CodeGenerationDatabaseProvider provider)
    {
        if (!type.IsClass || type.IsAbstract || type.IsGenericType)
            throw new NotSupportedException($"Parameter type '{type}' requires a concrete property-based parameter object.");
        var properties = type.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(property => property.GetIndexParameters().Length == 0 && property.GetMethod?.IsPublic == true)
            .OrderBy(property => property.Name, StringComparer.Ordinal).ToArray();
        var body = new StringBuilder();
        foreach (var property in properties)
            body.AppendLine(GenerateProperty(property, provider));
        var prefix = provider switch
        {
            CodeGenerationDatabaseProvider.SqlServer => "Sql",
            CodeGenerationDatabaseProvider.PostgreSql => "Npgsql",
            CodeGenerationDatabaseProvider.MySql => "MySql",
            _ => throw new ArgumentOutOfRangeException(nameof(provider))
        };
        var method = provider == CodeGenerationDatabaseProvider.PostgreSql ? "AddNpgsqlParameter" : $"Add{prefix}Parameters";
        var parameterPrefix = provider == CodeGenerationDatabaseProvider.PostgreSql
            ? "    protected override string ParameterPrefix => string.Empty;\n\n" : string.Empty;
        return $$"""
            // <auto-generated/>
            #nullable enable
            using Paradigm.Enterprise.Data.{{provider}}.StoredProcedures.Mappers;

            namespace {{projectName}}.Data.Mappers.SqlParameters;

            {{StoredProcedureMapperGenerator.GeneratedAttribute()}}
            internal partial class {{type.Name}}Mapper : {{prefix}}ParameterMapperBase
            {
            {{parameterPrefix}}    protected override void {{method}}(object parameters)
                {
                    var instance = ({{StoredProcedureMapperGenerator.TypeName(type)}})parameters;
            {{body.ToString().TrimEnd()}}
                }
            }
            """;
    }

    #endregion

    #region Private Methods

    private static string GenerateProperty(PropertyInfo property, CodeGenerationDatabaseProvider provider)
    {
        var type = Nullable.GetUnderlyingType(property.PropertyType) ?? property.PropertyType;
        var value = $"instance.@{property.Name}";
        if (type.IsEnum)
        {
            var underlying = StoredProcedureMapperGenerator.TypeName(Enum.GetUnderlyingType(type));
            value = Nullable.GetUnderlyingType(property.PropertyType) is not null
                ? $"(instance.@{property.Name}.HasValue ? (object)({underlying})instance.@{property.Name}.Value : null)"
                : $"({underlying})instance.@{property.Name}";
            type = Enum.GetUnderlyingType(type);
        }
        if (provider == CodeGenerationDatabaseProvider.MySql)
        {
            var dbType = MySqlType(type) ?? throw new NotSupportedException(
                $"MySQL parameter property '{property.DeclaringType}.{property.Name}' requires an explicit custom mapper; arrays, composite values, and offset dates are not inferred.");
            return $$"""
                        AddMySqlParameter(new global::MySql.Data.MySqlClient.MySqlParameter("@{{property.Name}}", global::MySql.Data.MySqlClient.MySqlDbType.{{dbType}})
                        {
                            Value = (object?){{value}} ?? global::System.DBNull.Value
                        });
                """;
        }
        if (provider == CodeGenerationDatabaseProvider.PostgreSql)
        {
            if (!IsScalar(type) && !(type.IsArray && IsScalar(type.GetElementType()!)))
                throw new NotSupportedException($"PostgreSQL parameter property '{property.DeclaringType}.{property.Name}' requires an explicit composite mapper.");
            return $"        AddNpgsqlParameter(nameof(instance.@{property.Name}), {value});";
        }
        if (!IsScalar(type))
            return GenerateTableProperty(property);
        return $"        AddSqlParameter(nameof(instance.@{property.Name}), {value});";
    }

    private static string GenerateTableProperty(PropertyInfo property)
    {
        var collection = property.PropertyType.IsGenericType &&
            property.PropertyType.GetGenericTypeDefinition() == typeof(IEnumerable<>);
        var itemType = collection ? property.PropertyType.GetGenericArguments()[0] : property.PropertyType;
        var properties = itemType.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(item => item.GetIndexParameters().Length == 0 && item.GetMethod?.IsPublic == true)
            .OrderBy(item => item.Name, StringComparer.Ordinal).ToArray();
        if (properties.Length == 0 || properties.Any(item => !IsScalar(Nullable.GetUnderlyingType(item.PropertyType) ?? item.PropertyType)))
            throw new NotSupportedException($"SQL Server table parameter '{property.DeclaringType}.{property.Name}' needs an explicit mapper.");
        var source = new StringBuilder();
        source.AppendLine($"        if (instance.@{property.Name} is not null)");
        source.AppendLine("        {");
        source.AppendLine("            var table = new global::System.Data.DataTable();");
        foreach (var item in properties)
            source.AppendLine($"            table.Columns.Add(\"{item.Name}\", typeof({StoredProcedureMapperGenerator.TypeName(Nullable.GetUnderlyingType(item.PropertyType) ?? item.PropertyType)}));");
        if (collection)
        {
            source.AppendLine($"            foreach (var item in instance.@{property.Name})");
            source.AppendLine("            {");
        }
        var indent = collection ? "                " : "            ";
        source.AppendLine($"{indent}var row = table.NewRow();");
        foreach (var item in properties)
            source.AppendLine($"{indent}row[\"{item.Name}\"] = (object?){(collection ? "item" : "instance.@" + property.Name)}.@{item.Name} ?? global::System.DBNull.Value;");
        source.AppendLine($"{indent}table.Rows.Add(row);");
        if (collection)
            source.AppendLine("            }");
        source.AppendLine($"            AddSqlParameter(nameof(instance.@{property.Name}), table);");
        source.Append("        }");
        return source.ToString();
    }

    private static bool IsScalar(Type type) => type.IsPrimitive || type.IsEnum ||
        type == typeof(string) || type == typeof(decimal) || type == typeof(Guid) ||
        type == typeof(DateTime) || type == typeof(DateTimeOffset) || type == typeof(TimeSpan) || type == typeof(byte[]);

    private static string? MySqlType(Type type) =>
        type == typeof(string) || type == typeof(char) ? "VarChar" :
        type == typeof(int) ? "Int32" : type == typeof(long) ? "Int64" :
        type == typeof(short) ? "Int16" : type == typeof(byte) ? "UByte" :
        type == typeof(sbyte) ? "Byte" : type == typeof(ushort) ? "UInt16" :
        type == typeof(uint) ? "UInt32" : type == typeof(ulong) ? "UInt64" :
        type == typeof(bool) ? "Byte" : type == typeof(decimal) ? "Decimal" :
        type == typeof(double) ? "Double" : type == typeof(float) ? "Float" :
        type == typeof(Guid) ? "Guid" : type == typeof(DateTime) ? "DateTime" :
        type == typeof(TimeSpan) ? "Time" : type == typeof(byte[]) ? "Blob" : null;

    #endregion
}