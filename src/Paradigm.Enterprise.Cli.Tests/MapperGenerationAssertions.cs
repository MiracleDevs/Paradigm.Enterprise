internal static class MapperGenerationAssertions
{
    #region Public Methods

    public static string FixtureAssembly(string repository)
    {
        var configuration = new DirectoryInfo(AppContext.BaseDirectory).Parent!.Name;
        return Path.Combine(repository, "src", "Paradigm.Enterprise.Cli.Tests", "Fixtures", "GeneratorFixtures", "bin", configuration, "net10.0", "GeneratorFixtures.dll");
    }

    public static Dictionary<string, byte[]> Snapshot(string output) => Directory
        .EnumerateFiles(output, "*.cs", SearchOption.AllDirectories)
        .ToDictionary(path => Path.GetRelativePath(output, path), File.ReadAllBytes, StringComparer.Ordinal);

    public static void AssertSameFiles(Dictionary<string, byte[]> before, string output)
    {
        var after = Snapshot(output);
        CollectionAssert.AreEquivalent(before.Keys.ToArray(), after.Keys.ToArray());
        foreach (var (path, content) in before)
            CollectionAssert.AreEqual(content, after[path], path);
    }

    public static async Task AssertCompilesAndMapsAsync(string fixtureAssembly, string output, string provider)
    {
        var inputName = provider switch
        {
            "mysql" => "Input",
            "postgresql" => "PostgreSqlInput",
            _ => "SqlServerInput"
        };
        var parameterFile = Path.Combine(output, "Mappers", "SqlParameters", inputName + "Mapper.cs");
        Assert.IsTrue(File.Exists(parameterFile), parameterFile);
        Assert.IsTrue(File.Exists(Path.Combine(output, "Mappers", "DataReaders", "ReportRowDataReaderMapper.cs")));
        foreach (var excluded in new[] { "Input", "SqlServerInput", "PostgreSqlInput" }.Where(name => name != inputName))
            Assert.IsFalse(File.Exists(Path.Combine(output, "Mappers", "SqlParameters", excluded + "Mapper.cs")), "Generation crossed the selected provider boundary.");

        var generated = Snapshot(output).Where(file => !file.Key.EndsWith("Handwritten.partial.cs", StringComparison.Ordinal)).ToArray();
        foreach (var (_, content) in generated)
        {
            var source = System.Text.Encoding.UTF8.GetString(content);
            StringAssert.Contains(source, "<auto-generated/>");
            StringAssert.Contains(source, "GeneratedCode");
            Assert.IsFalse(source.Contains(".Data.Core.", StringComparison.Ordinal), "Generated sources reference an obsolete application-local framework namespace.");
        }

        var fixtureDirectory = Path.GetDirectoryName(fixtureAssembly)!;
        var fixture = Assembly.LoadFrom(fixtureAssembly);
        var assembly = CompileGenerated(fixtureAssembly, output);
        var registerer = assembly.GetType("MapperFixture.Data.Mappers.StoreProcedureMappersRegisterer", throwOnError: true)!;
        registerer.GetMethod("RegisterMappers")!.Invoke(null, null);

        var adapter = provider switch { "mysql" => "MySql", "postgresql" => "PostgreSql", _ => "SqlServer" };
        var factoryName = provider switch { "mysql" => "MySqlParameterMapperFactory", "postgresql" => "NpgsqlParameterMapperFactory", _ => "SqlParameterMapperFactory" };
        var adapterAssembly = Assembly.LoadFrom(Path.Combine(fixtureDirectory, "Paradigm.Enterprise.Data." + adapter + ".dll"));
        var factory = adapterAssembly.GetType("Paradigm.Enterprise.Data." + adapter + ".StoredProcedures." + factoryName, throwOnError: true)!;
        var inputType = fixture.GetType("MapperFixture." + inputName, throwOnError: true)!;
        var input = Activator.CreateInstance(inputType)!;
        inputType.GetProperty("CategoryId")!.SetValue(input, 42);
        inputType.GetProperty("Name")!.SetValue(input, null);
        var token = Guid.NewGuid();
        inputType.GetProperty("Token")?.SetValue(input, token);
        using (var registered = (IDisposable)factory.GetMethod("GetMapper", [typeof(Type)])!.Invoke(null, [inputType])!)
        {
            Assert.AreEqual(inputName + "Mapper", registered.GetType().Name);
            StringAssert.StartsWith(registered.GetType().BaseType!.FullName!, "Paradigm.Enterprise.Data." + adapter + ".StoredProcedures.Mappers.");
        }
        using (var mapper = (IDisposable)Activator.CreateInstance(assembly.GetType("MapperFixture.Data.Mappers.SqlParameters." + inputName + "Mapper", throwOnError: true)!)!)
        {
            var parameters = ((Array)mapper.GetType().GetMethod("Map")!.Invoke(mapper, [input])!).Cast<DbParameter>().ToArray();
            Assert.AreEqual(42, parameters.Single(parameter => parameter.ParameterName.EndsWith("CategoryId", StringComparison.Ordinal)).Value);
            Assert.AreEqual(DBNull.Value, parameters.Single(parameter => parameter.ParameterName.EndsWith("Name", StringComparison.Ordinal)).Value);
            if (provider == "mysql")
            {
                Assert.AreEqual(token, parameters.Single(parameter => parameter.ParameterName == "@Token").Value);
                Assert.AreEqual(DBNull.Value, parameters.Single(parameter => parameter.ParameterName == "@Amount").Value);
                Assert.AreEqual(DBNull.Value, parameters.Single(parameter => parameter.ParameterName == "@SinceUtc").Value);
            }
        }

        var readerMapper = Activator.CreateInstance(assembly.GetType("MapperFixture.Data.Mappers.DataReaders.ReportRowDataReaderMapper", throwOnError: true)!)!;
        using var table = new DataTable();
        table.Columns.Add("Id", typeof(int));
        table.Columns.Add("Token", typeof(Guid));
        table.Columns.Add("Name", typeof(string));
        table.Columns.Add("Amount", typeof(decimal));
        table.Columns.Add("OccurredAt", typeof(DateTime));
        table.Columns.Add("Enabled", typeof(bool));
        table.Columns.Add("Payload", typeof(byte[]));
        var date = new DateTime(2026, 11, 13, 12, 0, 0, DateTimeKind.Utc);
        table.Rows.Add(7, token, DBNull.Value, 12.3456m, date, true, new byte[] { 0, 128, 255 });
        using var reader = table.CreateDataReader();
        Assert.IsTrue(reader.Read());
        var result = readerMapper.GetType().GetMethod("Map")!.Invoke(readerMapper, [reader])!;
        Assert.AreEqual(7, result.GetType().GetProperty("Id")!.GetValue(result));
        Assert.AreEqual(token, result.GetType().GetProperty("Token")!.GetValue(result));
        Assert.IsNull(result.GetType().GetProperty("Name")!.GetValue(result));
        Assert.AreEqual(12.3456m, result.GetType().GetProperty("Amount")!.GetValue(result));
        Assert.AreEqual(date, result.GetType().GetProperty("OccurredAt")!.GetValue(result));
        Assert.AreEqual(true, result.GetType().GetProperty("Enabled")!.GetValue(result));
        CollectionAssert.AreEqual(new byte[] { 0, 128, 255 }, (byte[])result.GetType().GetProperty("Payload")!.GetValue(result)!);

        if (provider == "mysql")
        {
            foreach (var (name, type, value) in new (string, Type, object)[]
            {
                ("String", typeof(string), "scalar"), ("Decimal", typeof(decimal), 12.34m),
                ("Guid", typeof(Guid), token), ("DateTime", typeof(DateTime), date),
                ("Int32Nullable", typeof(int), 17), ("Int32", typeof(int), 11)
            })
            {
                var scalarMapper = Activator.CreateInstance(assembly.GetType("MapperFixture.Data.Mappers.DataReaders." + name + "DataReaderMapper", throwOnError: true)!)!;
                using var scalarTable = new DataTable();
                scalarTable.Columns.Add("Value", type);
                scalarTable.Rows.Add(value);
                scalarTable.Rows.Add(DBNull.Value);
                using var scalarReader = scalarTable.CreateDataReader();
                Assert.IsTrue(scalarReader.Read());
                Assert.AreEqual(value, scalarMapper.GetType().GetMethod("Map")!.Invoke(scalarMapper, [scalarReader]), name);
                if (name == "Int32Nullable")
                {
                    Assert.IsTrue(scalarReader.Read());
                    Assert.IsNull(scalarMapper.GetType().GetMethod("Map")!.Invoke(scalarMapper, [scalarReader]));
                }
            }

            using var listTable = new DataTable();
            listTable.Columns.Add("Value", typeof(int));
            listTable.Rows.Add(3);
            listTable.Rows.Add(9);
            using var listReader = listTable.CreateDataReader();
            var coreAssembly = Assembly.LoadFrom(Path.Combine(fixtureDirectory, "Paradigm.Enterprise.Data.dll"));
            var extensions = coreAssembly.GetType("Paradigm.Enterprise.Data.Extensions.DbDataReaderExtensions", throwOnError: true)!;
            var translate = extensions.GetMethod("TranslateAsync")!.MakeGenericMethod(typeof(List<int>));
            var task = (Task)translate.Invoke(null, [listReader])!;
            await task;
            var values = (List<int>)task.GetType().GetProperty("Result")!.GetValue(task)!;
            CollectionAssert.AreEqual(new[] { 3, 9 }, values);
        }
    }

    public static Assembly CompileGenerated(string fixtureAssembly, string output)
    {
        LoadFixtureDependencies(fixtureAssembly);
        using var image = new MemoryStream(Compile(
            fixtureAssembly,
            Snapshot(output).Select(file => CSharpSyntaxTree.ParseText(System.Text.Encoding.UTF8.GetString(file.Value), path: file.Key))));
        return AssemblyLoadContext.Default.LoadFromStream(image);
    }

    public static string WriteFixture(string fixtureAssembly, string directory, string source)
    {
        LoadFixtureDependencies(fixtureAssembly);
        Directory.CreateDirectory(directory);
        foreach (var dependency in Directory.EnumerateFiles(Path.GetDirectoryName(fixtureAssembly)!, "*.dll"))
            File.Copy(dependency, Path.Combine(directory, Path.GetFileName(dependency)));
        var path = Path.Combine(directory, "FocusedFixture.dll");
        var contents = Compile(fixtureAssembly, [CSharpSyntaxTree.ParseText(source)]);
        File.WriteAllBytes(path, contents);
        // Preload the unique fixture identity from memory. Production LoadFrom then reuses it without
        // retaining a Windows file lock on the temporary assembly that this test must delete.
        using var image = new MemoryStream(contents);
        AssemblyLoadContext.Default.LoadFromStream(image);
        return path;
    }

    #endregion

    #region Private Methods

    private static void LoadFixtureDependencies(string fixtureAssembly)
    {
        var resolver = new AssemblyDependencyResolver(Path.GetFullPath(fixtureAssembly));
        foreach (var path in Directory.EnumerateFiles(Path.GetDirectoryName(fixtureAssembly)!, "*.dll"))
        {
            var name = AssemblyName.GetAssemblyName(path);
            if (AssemblyLoadContext.Default.Assemblies.Any(assembly => string.Equals(assembly.GetName().Name, name.Name, StringComparison.OrdinalIgnoreCase)))
                continue;
            // Resolve the fixture's managed runtime assets before loading portable facades such as
            // SqlClient's root DLL. The deps resolver chooses the current Windows or Unix implementation.
            var runtimePath = resolver.ResolveAssemblyToPath(name) ?? Path.GetFullPath(path);
            AssemblyLoadContext.Default.LoadFromAssemblyPath(runtimePath);
        }
    }

    private static byte[] Compile(string fixtureAssembly, IEnumerable<SyntaxTree> trees)
    {
        var references = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var path in ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator))
            references[Path.GetFileName(path)] = path;
        foreach (var path in Directory.EnumerateFiles(Path.GetDirectoryName(fixtureAssembly)!, "*.dll"))
            references[Path.GetFileName(path)] = path;
        var compilation = CSharpCompilation.Create(
            "GeneratedMapperContract" + Guid.NewGuid().ToString("N"), trees,
            references.Values.Select(path => MetadataReference.CreateFromFile(path)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        using var image = new MemoryStream();
        var emitted = compilation.Emit(image);
        Assert.IsTrue(emitted.Success, string.Join(Environment.NewLine, emitted.Diagnostics));
        Assert.IsFalse(emitted.Diagnostics.Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Warning), string.Join(Environment.NewLine, emitted.Diagnostics));
        return image.ToArray();
    }

    #endregion
}